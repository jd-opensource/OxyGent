    let currentLang = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
    if (!SUPPORTED.includes(currentLang)) currentLang = DEFAULT_LANG;

    function t(key, fallback) {
        const dict = TRANSLATIONS[currentLang] || TRANSLATIONS[DEFAULT_LANG];
        return dict[key] || fallback || TRANSLATIONS['en'][key] || key;
    }

    function setLang(lang) {
        if (!SUPPORTED.includes(lang)) return;
        currentLang = lang;
        localStorage.setItem(STORAGE_KEY, lang);
        apply();
        $(document).trigger('oxybank:lang-change', [lang]);
    }

    function getLang() { return currentLang; }

    function apply() {
        $('[data-i18n]').each(function () {
            const key = $(this).attr('data-i18n');
            $(this).text(t(key));
        });
        $('[data-i18n-placeholder]').each(function () {
            const key = $(this).attr('data-i18n-placeholder');
            $(this).attr('placeholder', t(key));
        });
        $('[data-i18n-title]').each(function () {
            const key = $(this).attr('data-i18n-title');
            $(this).attr('title', t(key));
        });
        // Update lang toggle buttons
        $('.lang-toggle button').removeClass('active');
        $(`.lang-toggle button[data-lang="${currentLang}"]`).addClass('active');
    }

    global.i18n = { t, setLang, getLang, apply, TRANSLATIONS };
